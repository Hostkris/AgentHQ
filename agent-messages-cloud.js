let syncGeneration=0;
let unreadGeneration=0;
const employees = new Set(['alex','maya','jordan','riley','taylor','casey','morgan','avery','jamie','quinn','hq']);
async function getUser() {
  const {data,error}=await agentCloud.auth.getUser();
  if(error)throw Error(error.name==='AuthSessionMissingError'?'Sign in under Settings to sync messages.':error.message);
  if(!data?.user)throw Error('Sign in under Settings to sync messages.');
  return data.user;
}
function parseUnread(rows){
 const counts={};
 for(const row of rows||[]){
  if(!employees.has(row.employee_id))continue;
  const n=Number(row.unread_count);
  if(Number.isFinite(n)&&n>0)counts[row.employee_id]=n;
 }
 return counts;
}
// Counts are generated by an owner-scoped database function, not from the capped history preview.
async function refreshUnread(){
 const generation=++unreadGeneration;
 try{
  await getUser();
  const {data,error}=await agentCloud.rpc('get_agent_unread_counts');
  if(error)throw Error(error.message);
  if(generation!==unreadGeneration)return;
  let counts=parseUnread(data);
  const visible=window.agentHQVisibleThread?.();
  if(visible&&counts[visible]){
   // A conversation currently visible to the owner counts as read.
   const {error:readError}=await agentCloud.rpc('mark_agent_conversation_read',{p_employee_id:visible});
   if(!readError){
    const latest=await agentCloud.rpc('get_agent_unread_counts');
    if(!latest.error)counts=parseUnread(latest.data);
   }
  }
  if(generation===unreadGeneration)window.agentHQUnreadSync?.(counts);
 }catch(error){
  if(generation===unreadGeneration)window.agentHQUnreadError?.('Unread counts unavailable: '+error.message);
 }
}
async function markRead(employeeId){
 if(!employees.has(employeeId))throw Error('Unknown conversation');
 await getUser();
 const {error}=await agentCloud.rpc('mark_agent_conversation_read',{p_employee_id:employeeId});
 if(error)throw Error('Could not mark conversation as read: '+error.message);
 await refreshUnread();
}
async function refresh() {
  const generation=++syncGeneration;
  let user;
  try {user=await getUser()}catch(e){if(generation===syncGeneration){window.agentHQSyncMessages?.([],e.message);window.agentHQUnreadSync?.({});}return}
  if(generation!==syncGeneration)return;
  const {data:chats,error:chatError}=await agentCloud.from('agent_conversations').select('id,employee_id,cleared_at');
  if(generation!==syncGeneration)return;
  if(chatError)throw Error(chatError.message);
  const valid=(chats||[]).filter(c=>employees.has(c.employee_id));
  window.agentHQConversationClearSync?.(Object.fromEntries(valid.map(c=>[c.employee_id,c.cleared_at||null])));
  if(!valid.length){window.agentHQSyncMessages?.([],'No saved text messages yet.');await refreshUnread();return}
  const {data:items,error:messageError}=await agentCloud.from('agent_messages').select('id,conversation_id,sender,body,created_at').in('conversation_id',valid.map(x=>x.id)).order('created_at',{ascending:false}).limit(1000);
  if(generation!==syncGeneration)return;
  if(messageError)throw Error(messageError.message);
  const mapping=new Map(valid.map(x=>[x.id,x.employee_id]));
  window.agentHQSyncMessages?.((items||[]).reverse().map(x=>({id:x.id,employeeId:mapping.get(x.conversation_id),sender:x.sender,text:x.body,createdAt:x.created_at})).filter(x=>x.employeeId),'Text messages saved in Agent HQ.');
  await refreshUnread();
}
async function send(employeeId,body) {
  if(!employees.has(employeeId))throw Error('Invalid employee.');
  body=String(body||'').trim();
  if(!body||body.length>20000)throw Error('Enter a message under 20,000 characters.');
  await getUser();
  // The server validates ownership and inserts the conversation and text atomically.
  const {data:id,error}=await agentCloud.rpc('send_agent_owner_message',{
    p_employee_id:employeeId,
    p_body:body
  });
  if(error)throw Error('Could not save your message: '+error.message);
  if(!id)throw Error('The server did not confirm the saved message.');
  return {id,employeeId,text:body,sender:'owner'};
}
async function converse(employeeId,body,options={}){
 if(!employees.has(employeeId))throw Error('Unknown employee');
 body=String(body||'').trim();
 if(!body||body.length>10000)throw Error('Message must be 1–10,000 characters.');
 await getUser();
 if(!options.research&&employeeId==='riley'){
  if(window.agentHQSocialReadCloud?.handleChat){const result=await window.agentHQSocialReadCloud.handleChat(body);if(result.handled)return result;}
  else if(/\b(facebook|messenger)\b/i.test(body))throw Error('Riley’s Facebook reader is loading. Refresh this conversation and try again.');
 }
 const {data,error}=await agentCloud.functions.invoke('agent-hq-converse',{
  body:{employee_id:employeeId,text:body,...(options.research?{action:"role_research"}:{}),
   ...(options.projectId?{project_id:options.projectId}:{}),...(options.projectVersion?{output_version:options.projectVersion}:{}),
   ...(options.projectRevision?{project_revision:options.projectRevision}:{})}
 });
 if(error){
  let reason=data?.error;
  if(!reason&&error.context?.clone){try{reason=(await error.context.clone().json())?.error}catch{}}
  throw Error(reason||error.message||'Worker chat is unavailable.');
 }
 if(!data?.success)throw Error(data?.error||'The worker chat was not confirmed.');
 await refresh();
 await window.agentHQResearchCloud?.refresh?.().catch(()=>{});
 return data;
}
async function deleteMessage(messageId){
 await getUser();
 const {data,error}=await agentCloud.rpc('delete_agent_chat_message',{p_message_id:messageId});
 if(error||data!==true)throw Error(error?.message||'Message could not be deleted');
 await refresh();
 return true;
}
async function deleteMessages(ids){
 await getUser();
 const unique=[...new Set(ids.map(String))];
 if(!unique.length)return 0;
 let deleted=0;
 // Each deletion is still owner-validated by the database RPC.
 for(let index=0;index<unique.length;index+=6){
  const batch=unique.slice(index,index+6);
  const outcomes=await Promise.all(batch.map(p_message_id=>agentCloud.rpc('delete_agent_chat_message',{p_message_id})));
  for(let n=0;n<outcomes.length;n++){
   const result=outcomes[n];
   if(result.error||result.data!==true){
    await refresh().catch(()=>{});
    throw Error('Deleted '+deleted+' of '+unique.length+' messages. '+(result.error?.message||'A message could not be deleted.'));
   }
   deleted++;
  }
 }
 await refresh();return deleted;
}
async function clearConversation(employeeId){
 if(!employees.has(employeeId))throw Error('Unknown worker conversation');
 await getUser();
 // Owner-initiated thread deletion also clears its private image attachments.
 await window.agentHQCamera?.clearThread?.(employeeId);
 const {data,error}=await agentCloud.rpc('clear_agent_conversation',{p_employee_id:employeeId});
 if(error)throw Error('Could not clear this conversation: '+error.message);
 await refresh();
 return Number(data||0);
}
